#!/usr/bin/env node
// Writes src/environments/environment.production.ts from NG_APP_* env vars (runs as the `prebuild` hook).
//  - All six set: validated and written (the deploy workflow path).
//  - None set: a clearly-marked placeholder is written so CI / local builds still compile (a warning is printed).
//  - Some set: hard error, so a half-configured deploy never ships.
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { assertProdApiBaseUrl } from './lib/assert-prod-api-base-url.mjs';

const REQUIRED = [
  'NG_APP_API_BASE_URL',
  'NG_APP_COGNITO_REGION',
  'NG_APP_COGNITO_USER_POOL_ID',
  'NG_APP_COGNITO_CLIENT_ID',
  'NG_APP_COGNITO_DOMAIN',
  'NG_APP_COGNITO_REDIRECT_URI',
];

const missing = REQUIRED.filter((name) => !process.env[name]);
const placeholder = missing.length === REQUIRED.length;

if (!placeholder && missing.length > 0) {
  console.error(`build-env: missing required env vars: ${missing.join(', ')}`);
  process.exit(1);
}

const get = (name, fallback) => (placeholder ? fallback : process.env[name]);

if (placeholder) {
  console.warn('build-env: no NG_APP_* variables set; writing a PLACEHOLDER production environment (not deployable).');
} else {
  assertProdApiBaseUrl(process.env.NG_APP_API_BASE_URL, { allowLocal: process.env.ALLOW_LOCAL_API_URL === '1' });
}

const env = {
  production: true,
  apiBaseUrl: get('NG_APP_API_BASE_URL', 'https://api.nabbit.invalid'),
  // Optional (outside the all-or-nothing set): defaults to the same-origin CloudFront /img/* path.
  imageBaseUrl: (process.env.NG_APP_IMAGE_BASE_URL || '/img').replace(/\/+$/, ''),
  cognito: {
    region: get('NG_APP_COGNITO_REGION', 'ap-southeast-2'),
    userPoolId: get('NG_APP_COGNITO_USER_POOL_ID', 'ap-southeast-2_placeholder'),
    clientId: get('NG_APP_COGNITO_CLIENT_ID', 'placeholder'),
    domain: get('NG_APP_COGNITO_DOMAIN', 'auth.nabbit.invalid'),
    redirectUri: get('NG_APP_COGNITO_REDIRECT_URI', 'https://nabbit.invalid/callback'),
  },
  disableAuth: false,
};

const __dirname = dirname(fileURLToPath(import.meta.url));
const outPath = resolve(__dirname, '../src/environments/environment.production.ts');
const banner = '// Generated by scripts/build-env.mjs -- do not edit by hand.';
const body = `import type { Environment } from './environment.types';\n\nexport const environment: Environment = ${JSON.stringify(env, null, 2)};\n`;

writeFileSync(outPath, `${banner}\n\n${body}`, 'utf8');
console.log(`build-env: wrote ${outPath}`);
