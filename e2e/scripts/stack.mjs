// Starts / stops the local e2e stack. Everything it creates is named or recorded so `down` removes exactly that.
//   up:   LocalStack container -> init-local -> built frontend (static) + fixture site (static) + backend
//   down: kills the recorded processes and removes the container
// Ports (env, all optional): E2E_LOCALSTACK_PORT 4577, E2E_BACKEND_PORT 3010, E2E_FRONTEND_PORT 4210, E2E_FIXTURE_PORT 4211.
// It never touches other containers or ports; pick different ports if one is busy.
import { execFileSync, spawn } from 'node:child_process';
import { existsSync, mkdirSync, openSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { setTimeout as sleep } from 'node:timers/promises';
import { ports } from './ports.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const e2eDir = resolve(here, '..');
const repo = resolve(e2eDir, '..');
const stateDir = join(e2eDir, '.stack');
const stateFile = join(stateDir, 'state.json');
const { localstack, backend, frontend, fixture, container, table, bucket } = ports;
const isWin = process.platform === 'win32';

const docker = (...args) => execFileSync('docker', args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });

async function waitFor(url, label, ms = 120_000) {
  const end = Date.now() + ms;
  while (Date.now() < end) {
    try {
      if ((await fetch(url)).ok) return;
    } catch {
      /* not up yet */
    }
    await sleep(500);
  }
  throw new Error(`${label} did not become ready at ${url}`);
}

function killTree(pid) {
  try {
    if (isWin) execFileSync('taskkill', ['/pid', String(pid), '/T', '/F'], { stdio: 'ignore' });
    else process.kill(-pid, 'SIGTERM');
  } catch {
    /* already gone */
  }
}

function launch(name, cmd, args, opts) {
  const log = openSync(join(stateDir, `${name}.log`), 'w');
  const child = spawn(cmd, args, { ...opts, detached: true, stdio: ['ignore', log, log], windowsHide: true });
  child.unref();
  return child.pid;
}

function down() {
  if (existsSync(stateFile)) {
    const { pids } = JSON.parse(readFileSync(stateFile, 'utf8'));
    for (const pid of pids) killTree(pid);
    rmSync(stateFile, { force: true });
  }
  try {
    docker('rm', '-f', container);
    console.log(`removed container ${container}`);
  } catch {
    /* none */
  }
}

async function up() {
  down(); // only ever our own recorded pids / named container
  mkdirSync(stateDir, { recursive: true });
  const pids = [];
  const save = () => writeFileSync(stateFile, JSON.stringify({ pids }));
  try {
    docker(
      'run', '-d', '--name', container, '--label', 'nabbit-e2e=1',
      '-p', `127.0.0.1:${localstack}:4566`,
      '-e', 'SERVICES=s3,dynamodb', '-e', 'LOCALSTACK_ACKNOWLEDGE_ACCOUNT_REQUIREMENT=1',
      'localstack/localstack:3',
    );
    await waitFor(`http://127.0.0.1:${localstack}/_localstack/health`, 'LocalStack');

    const awsEnv = {
      AWS_REGION: 'us-east-1',
      AWS_ACCESS_KEY_ID: 'test',
      AWS_SECRET_ACCESS_KEY: 'test',
      AWS_ENDPOINT_URL: `http://127.0.0.1:${localstack}`,
      TABLE_NAME: table,
      IMAGE_BUCKET: bucket,
    };
    execFileSync('node', ['scripts/init-local.mjs'], { cwd: join(repo, 'backend'), env: { ...process.env, ...awsEnv }, stdio: 'inherit' });

    // Frontend: dev environment (auth disabled, mock token) pointed at OUR backend port, built once and served statically.
    writeFileSync(
      join(repo, 'frontend/src/environments/environment.e2e.ts'),
      [
        '// Generated by e2e/scripts/stack.mjs -- not committed.',
        "import type { Environment } from './environment.types';",
        '',
        'export const environment: Environment = {',
        '  production: false,',
        `  apiBaseUrl: 'http://127.0.0.1:${backend}',`,
        `  imageBaseUrl: 'http://127.0.0.1:${localstack}/${bucket}',`,
        `  cognito: { region: 'us-east-1', userPoolId: 'us-east-1_testPoolId0', clientId: 'testclientid1234567890ab', domain: 'auth.dev.nabbit.local', redirectUri: 'http://127.0.0.1:${frontend}/callback' },`,
        '  disableAuth: true,',
        '};',
        '',
      ].join('\n'),
    );
    const ng = join(repo, 'node_modules/@angular/cli/bin/ng.js');
    execFileSync('node', [ng, 'build', '--configuration', 'e2e', '--output-path', join(e2eDir, '.dist')], { cwd: join(repo, 'frontend'), stdio: 'inherit' });

    const serve = join(here, 'static-server.mjs');
    pids.push(launch('frontend', 'node', [serve, join(e2eDir, '.dist/browser'), String(frontend), '--spa'], { cwd: e2eDir }));
    save();
    pids.push(launch('fixture', 'node', [serve, join(e2eDir, 'fixtures/site'), String(fixture)], { cwd: e2eDir }));
    save();
    pids.push(
      launch('backend', 'node', ['--import', 'tsx', 'src/local.ts'], {
        cwd: join(repo, 'backend'),
        env: {
          ...process.env,
          ...awsEnv,
          NODE_ENV: 'development',
          PORT: String(backend),
          ALLOWED_ORIGIN: `http://127.0.0.1:${frontend}`,
          IMAGE_BASE_URL: `http://127.0.0.1:${localstack}/${bucket}`,
          NABBIT_E2E_FAKE_LLM: '1',
          NABBIT_E2E_FIXTURE_FETCH: '1',
          NABBIT_E2E_FIXTURE_ORIGIN: `http://127.0.0.1:${fixture}`,
        },
      }),
    );
    save();

    await waitFor(`http://127.0.0.1:${backend}/health`, 'backend');
    await waitFor(`http://127.0.0.1:${frontend}/`, 'frontend');
    await waitFor(`http://127.0.0.1:${fixture}/pasta.html`, 'fixture site');
    console.log(`stack up: frontend :${frontend}, backend :${backend}, fixtures :${fixture}, localstack :${localstack}`);
  } catch (e) {
    console.error(e);
    down();
    process.exit(1);
  }
}

const cmd = process.argv[2];
if (cmd === 'up') await up();
else if (cmd === 'down') down();
else {
  console.error('usage: stack.mjs up|down');
  process.exit(2);
}
